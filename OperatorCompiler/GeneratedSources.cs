using System.Text;

namespace T3.OperatorCompiler;

/// <summary>
/// The sources the .NET SDK generates into obj/ for every build, character for character (including the platform's
/// line endings), so diagnostics point at the same lines as with `dotnet build`.
/// </summary>
internal static class GeneratedSources
{
    public static string GlobalUsings(EvaluatedProject project)
    {
        var usings = new List<EvaluatedProject.UsingItem>();
        var implicitUsings = project.Get("ImplicitUsings");
        if (implicitUsings.Equals("enable", StringComparison.OrdinalIgnoreCase) || implicitUsings.Equals("true", StringComparison.OrdinalIgnoreCase))
        {
            foreach (var ns in _implicitUsingsOfSdk)
                usings.Add(new EvaluatedProject.UsingItem(ns, null, false));
        }

        usings.AddRange(project.Usings);
        usings = usings.Distinct().ToList();

        var builder = new StringBuilder("// <auto-generated/>\n");
        foreach (var u in usings.Where(u => u.Alias == null && !u.IsStatic).OrderBy(u => u.Namespace, StringComparer.Ordinal))
            builder.Append("global using ").Append(u.Namespace).Append(";\n");
        foreach (var u in usings.Where(u => u.Alias != null).OrderBy(u => u.Alias, StringComparer.Ordinal))
            builder.Append("global using ").Append(u.Alias).Append(" = ").Append(u.Namespace).Append(";\n");
        foreach (var u in usings.Where(u => u.Alias == null && u.IsStatic).OrderBy(u => u.Namespace, StringComparer.Ordinal))
            builder.Append("global using static ").Append(u.Namespace).Append(";\n");
        return WithPlatformLineEndings(builder.ToString());
    }

    public static string? AssemblyInfo(EvaluatedProject project)
    {
        if (project.Get("GenerateAssemblyInfo").Equals("false", StringComparison.OrdinalIgnoreCase))
            return null;

        var name = project.AssemblyName;
        var builder = new StringBuilder("""
                                        //------------------------------------------------------------------------------
                                        // <auto-generated>
                                        //     This code was generated by a tool.
                                        //
                                        //     Changes to this file may cause incorrect behavior and will be lost if
                                        //     the code is regenerated.
                                        // </auto-generated>
                                        //------------------------------------------------------------------------------

                                        using System;
                                        using System.Reflection;


                                        """);

        AddAttribute("AssemblyCompanyAttribute", project.Get("Company", name));
        AddAttribute("AssemblyConfigurationAttribute", project.Configuration);
        if (project.Get("Copyright").Length > 0)
            AddAttribute("AssemblyCopyrightAttribute", project.Get("Copyright"));
        if (project.Get("Description").Length > 0)
            AddAttribute("AssemblyDescriptionAttribute", project.Get("Description"));
        AddAttribute("AssemblyFileVersionAttribute", FourPartVersion(project.Get("FileVersion", project.VersionPrefix)));
        AddAttribute("AssemblyInformationalVersionAttribute", project.Get("InformationalVersion", project.Version));
        AddAttribute("AssemblyProductAttribute", project.Get("Product", name));
        AddAttribute("AssemblyTitleAttribute", project.Get("AssemblyTitle", name));
        AddAttribute("AssemblyVersionAttribute", FourPartVersion(project.Get("AssemblyVersion", project.VersionPrefix)));
        builder.Append("\n// Generated by the MSBuild WriteCodeFragment class.\n\n");
        return WithPlatformLineEndings(builder.ToString());

        void AddAttribute(string attribute, string value)
            => builder.Append("[assembly: System.Reflection.").Append(attribute).Append("(\"").Append(value.Replace("\"", "\\\"")).Append("\")]\n");
    }

    public static string TargetFrameworkAttribute => WithPlatformLineEndings(TargetFrameworkAttributeSource);

    private const string TargetFrameworkAttributeSource =
        """
        // <autogenerated />
        using System;
        using System.Reflection;
        [assembly: global::System.Runtime.Versioning.TargetFrameworkAttribute(".NETCoreApp,Version=v10.0", FrameworkDisplayName = ".NET 10.0")]

        """;

    public const string TargetFrameworkAttributeFileName = ".NETCoreApp,Version=v10.0.AssemblyAttributes.cs";

    /** The defines the SDK passes for a net10.0 build of the given configuration, after the project's own. */
    public static string[] PreprocessorSymbols(EvaluatedProject project)
    {
        var symbols = new List<string>(project.Get("DefineConstants").Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                          {
                              "TRACE",
                              project.IsDebugConfiguration ? "DEBUG" : "RELEASE",
                              "NET",
                              "NET10_0",
                              "NETCOREAPP",
                          };
        for (var major = 5; major <= 10; major++)
            symbols.Add($"NET{major}_0_OR_GREATER");

        symbols.AddRange(_netCoreAppVersionSymbols);
        return symbols.Distinct().ToArray();
    }

    private static string WithPlatformLineEndings(string text) => Environment.NewLine == "\n" ? text : text.Replace("\n", Environment.NewLine);

    private static string FourPartVersion(string version)
    {
        var parts = version.Split('-')[0].Split('.').ToList();
        while (parts.Count < 4)
            parts.Add("0");
        return string.Join('.', parts.Take(4));
    }

    private static readonly string[] _implicitUsingsOfSdk =
        ["System", "System.Collections.Generic", "System.IO", "System.Linq", "System.Net.Http", "System.Threading", "System.Threading.Tasks"];

    private static readonly string[] _netCoreAppVersionSymbols =
        [
            "NETCOREAPP1_0_OR_GREATER", "NETCOREAPP1_1_OR_GREATER", "NETCOREAPP2_0_OR_GREATER", "NETCOREAPP2_1_OR_GREATER",
            "NETCOREAPP2_2_OR_GREATER", "NETCOREAPP3_0_OR_GREATER", "NETCOREAPP3_1_OR_GREATER",
        ];
}
